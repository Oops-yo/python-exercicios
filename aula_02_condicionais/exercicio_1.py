"""

Proposta : 1. Faça um programa que receba dois números inteiros e mostre qual deles é o maior.

"""

print("Me dê o primeiro valor")
valor1 = int(input())

print("Me dê o segundo valor")
valor2 = int(input())

if valor1 > valor2:
    print(f"O {valor1} é o maior valor")

elif valor1 < valor2:
    print(f"O {valor2} é o maior valor")

else:
    print("Os valores são iguais")





