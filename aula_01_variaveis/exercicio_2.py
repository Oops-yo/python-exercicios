"""

Proposta:  Faça um programa que peça para o usuário digitar três valores inteiro e imprima a soma deles.

"""

print("Me dê o primeiro número")
numero_1 = int(input())

print("Me dê o segundo número")
numero_2 = int(input())

print("Me dê o terceiro número")
numero_3 = int(input())

resultado = numero_1 + numero_2 + numero_3
print(f"A soma de seus números é: {resultado}")
