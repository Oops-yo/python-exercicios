"""

Proposta:  Faça um programa que recebe três valores e apresente a soma dos quadrados dos valores lidos

"""

print("Informe o primeiro valor:")
valor1 = int(input())
print("Informe o segundo valor:")
valor2 = int(input())
print("Informe o terceiro valor:")
valor3 = int(input())

soma = (valor1 * valor1) + (valor2 * valor2) + (valor3 * valor3)

print(f"O resultado da soma do quadrados dos valores é {soma} ")